//! The server side of the adapter, as data: the generic Lua module (`server/ironhold.lua`, no build step) and a pure generator
//! for its config, called by `ironhold backend config <project>...`. No network code here; this module is available without
//! the `client` feature so the CLI never links an HTTP stack.
//!
//! Leaderboards can only be created by server code, so adding, renaming or removing one in a `backend.ron` needs a regenerated
//! config and a redeploy (a server-admin step). Renaming orphans the old scores.

use ironhold_core::schema::backend::{is_valid_backend_id, Keep, LeaderboardDef, Ranking};

/// The generic module. Deploy it as `ironhold.lua` next to the generated `ironhold_games.lua`.
pub const MODULE_LUA: &str = include_str!("../server/ironhold.lua");

/// File name the module expects for the generated config (`require("ironhold_games")`).
pub const GAMES_FILE: &str = "ironhold_games.lua";

/// One game's slice of the server config.
pub struct GameServerConfig<'a> {
    pub game_id: &'a str,
    pub leaderboards: &'a [LeaderboardDef],
}

fn sort_order(r: Ranking) -> &'static str {
    match r {
        Ranking::HigherIsBetter => "desc",
        Ranking::LowerIsBetter => "asc",
    }
}

fn operator(k: Keep) -> &'static str {
    match k {
        Keep::Best => "best",
        Keep::Latest => "set",
        Keep::Total => "incr",
    }
}

/// The text of `ironhold_games.lua`. Ids are re-checked here (they end up inside Lua string literals), and a `game_id` may
/// appear only once so two projects cannot silently share a namespace.
pub fn generate_games_lua(games: &[GameServerConfig]) -> Result<String, String> {
    let mut seen = std::collections::BTreeSet::new();
    let mut out = String::from("-- Generated by `ironhold backend config`. Do not edit; regenerate and redeploy instead.\nreturn {\n  games = {\n");
    let mut sorted: Vec<&GameServerConfig> = games.iter().collect();
    sorted.sort_by(|a, b| a.game_id.cmp(b.game_id));
    for g in sorted {
        if !is_valid_backend_id(g.game_id) {
            return Err(format!("game_id {:?} is not a valid id", g.game_id));
        }
        if !seen.insert(g.game_id) {
            return Err(format!("game_id {:?} is used by more than one project", g.game_id));
        }
        out.push_str(&format!("    {} = {{ leaderboards = {{\n", g.game_id));
        for lb in g.leaderboards {
            if !is_valid_backend_id(&lb.name) {
                return Err(format!("leaderboard {:?} is not a valid id", lb.name));
            }
            out.push_str(&format!(
                "      {{ id = \"{}.{}\", sort = \"{}\", operator = \"{}\" }},\n",
                g.game_id,
                lb.name,
                sort_order(lb.ranking),
                operator(lb.keep)
            ));
        }
        out.push_str("    } },\n");
    }
    out.push_str("  },\n}\n");
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use ironhold_core::schema::backend::BackendConfig;

    fn boards() -> Vec<LeaderboardDef> {
        let c: BackendConfig = ron::from_str(
            r#"BackendConfig(schema_version: 1, endpoint: Some("http://x"),
                leaderboards: [Leaderboard(name: "best", ranking: HigherIsBetter, keep: Best),
                               Leaderboard(name: "fast", ranking: LowerIsBetter, keep: Latest),
                               Leaderboard(name: "total", ranking: HigherIsBetter, keep: Total)])"#,
        )
        .unwrap();
        c.leaderboards
    }

    #[test]
    fn ranking_and_keep_map_to_nakama_sort_and_operator() {
        let b = boards();
        let lua = generate_games_lua(&[GameServerConfig { game_id: "my_game", leaderboards: &b }]).unwrap();
        assert!(lua.contains(r#"{ id = "my_game.best", sort = "desc", operator = "best" }"#), "{lua}");
        assert!(lua.contains(r#"{ id = "my_game.fast", sort = "asc", operator = "set" }"#), "{lua}");
        assert!(lua.contains(r#"{ id = "my_game.total", sort = "desc", operator = "incr" }"#), "{lua}");
    }

    #[test]
    fn output_is_sorted_and_duplicate_or_bad_games_are_refused() {
        let b = boards();
        let lua = generate_games_lua(&[
            GameServerConfig { game_id: "zeta", leaderboards: &b },
            GameServerConfig { game_id: "alpha", leaderboards: &b },
        ])
        .unwrap();
        assert!(lua.find("alpha").unwrap() < lua.find("zeta").unwrap());
        let dup = generate_games_lua(&[
            GameServerConfig { game_id: "a", leaderboards: &b },
            GameServerConfig { game_id: "a", leaderboards: &b },
        ]);
        assert!(dup.is_err());
        assert!(generate_games_lua(&[GameServerConfig { game_id: "a\"b", leaderboards: &b }]).is_err());
    }

    #[test]
    fn the_contract_fixture_is_what_the_generator_writes() {
        let c: BackendConfig = ron::from_str(
            r#"BackendConfig(schema_version: 1, endpoint: Some("http://x"),
                leaderboards: [Leaderboard(name: "best", ranking: HigherIsBetter, keep: Best),
                               Leaderboard(name: "fast", ranking: LowerIsBetter, keep: Latest)])"#,
        )
        .unwrap();
        let beta: BackendConfig = ron::from_str(
            r#"BackendConfig(schema_version: 1, endpoint: Some("http://x"),
                leaderboards: [Leaderboard(name: "best", ranking: HigherIsBetter, keep: Best)])"#,
        )
        .unwrap();
        let lua = generate_games_lua(&[
            GameServerConfig { game_id: "beta", leaderboards: &beta.leaderboards },
            GameServerConfig { game_id: "alpha", leaderboards: &c.leaderboards },
        ])
        .unwrap();
        let fixture = include_str!("../tests/contract/modules/ironhold_games.lua").replace("
", "
");
        assert_eq!(lua, fixture);
    }

    #[test]
    fn the_module_registers_the_game_id_hooks() {
        for name in ["AuthenticateDevice", "WriteLeaderboardRecord", "ListLeaderboardRecords", "WriteStorageObjects"] {
            assert!(MODULE_LUA.contains(name), "{name}");
        }
    }
}
